import 'dart:convert';

import 'google_form.dart';

/// 「Googleフォーム + Googleカレンダー」を一度に作る Google Apps Script を生成する。
/// 使う人は script.google.com に貼り付けて setup を 1 回実行するだけ：
///  1. 予約フォームを作る（質問・必須・選択肢はこのサイトのもの）
///  2. 予約専用のカレンダーを新しく作り、「予定あり（空き時間情報のみ）」を一般公開にする（予定の中身は非公開）
///  3. フォームが送信されるたびに、そのカレンダーへ予約の予定を作る（ダブルブッキングは目印を付ける）
/// 個人のカレンダーには一切触れない。値はすべて JSON として埋め込むので、質問文に引用符があっても壊れない。

class BookingScriptOptions {
  final String siteName;
  final String confirmation; // フォーム送信後に表示するメッセージ
  final int durationMinutes;
  final bool inviteCustomer; // true: 予約者のメールアドレスに予定の招待を送る
  const BookingScriptOptions({required this.siteName, required this.confirmation, this.durationMinutes = 60, this.inviteCustomer = false});
}

String bookingScript(List<SuggestedQuestion> questions, BookingScriptOptions o) {
  final qs = questions.take(30).toList();
  final config = const JsonEncoder.withIndent('  ').convert({
    'title': o.siteName,
    'description': o.siteName,
    'confirmation': o.confirmation,
    'calendarName': '${o.siteName} bookings',
    'durationMinutes': o.durationMinutes.clamp(10, 480),
    'inviteCustomer': o.inviteCustomer,
    'fields': [
      for (final q in qs) {'label': q.label, 'kind': q.kind, 'required': q.required, 'options': q.options},
    ],
  });
  return '''// Booking form + booking calendar for "${o.siteName.replaceAll(RegExp(r'[\r\n*/]'), ' ')}"
// Generated by Pricing AI. How to use:
//   1. Paste this whole script into https://script.google.com/create and press Save.
//   2. Optional but recommended: click "Services" (+) on the left, add "Google Calendar API". This lets the script make the calendar's Busy times public by itself.
//   3. Choose the function "setup" in the toolbar and press Run. Allow the permissions (it is your own script).
//   4. Open "Execution log", copy the line that starts with PASTE THIS INTO PRICING AI, and paste it into the app.
// What it does: creates the Google Form, creates a NEW calendar just for bookings and shares only its
// free/busy ("Busy") times publicly (event details stay private), and adds a calendar event for every form answer.
// Your own calendars are never changed.

const CONFIG = $config;

function setup() {
  const props = PropertiesService.getScriptProperties();

  // Re-running setup is safe: it reuses the form and calendar it already created.
  var form = null;
  if (props.getProperty('FORM_ID')) { try { form = FormApp.openById(props.getProperty('FORM_ID')); } catch (e) { form = null; } }
  if (!form) {
    form = FormApp.create(CONFIG.title);
    form.setDescription(CONFIG.description);
    form.setConfirmationMessage(CONFIG.confirmation);
    try { form.setCollectEmail(false); } catch (e) {}
    try { form.setRequireLogin(false); } catch (e) {}
    try { form.setLimitOneResponsePerUser(false); } catch (e) {}
    try { form.setAllowResponseEdits(false); } catch (e) {}
    CONFIG.fields.forEach(function (f) { addQuestion(form, f); });
    props.setProperty('FORM_ID', form.getId());
  }
  try { form.setAcceptingResponses(true); } catch (e) {}
  try { form.setPublished(true); } catch (e) {}

  var cal = null;
  if (props.getProperty('CAL_ID')) { try { cal = CalendarApp.getCalendarById(props.getProperty('CAL_ID')); } catch (e) { cal = null; } }
  if (!cal) {
    cal = CalendarApp.createCalendar(CONFIG.calendarName, { timeZone: Session.getScriptTimeZone() });
    props.setProperty('CAL_ID', cal.getId());
  }

  ScriptApp.getProjectTriggers().forEach(function (t) { if (t.getHandlerFunction() === 'onFormSubmit') ScriptApp.deleteTrigger(t); });
  ScriptApp.newTrigger('onFormSubmit').forForm(form).onFormSubmit().create();

  const shared = shareBusyPublicly(cal.getId());
  if (shared) {
    Logger.log('PASTE THIS INTO PRICING AI: ' + form.getPublishedUrl() + ' calendar:' + cal.getId());
  } else {
    Logger.log('PASTE THIS INTO PRICING AI: ' + form.getPublishedUrl());
    Logger.log('The calendar "' + CONFIG.calendarName + '" is created but its Busy times are not public yet. Either add the "Google Calendar API" service (left side "Services" +) and run setup again, or in Google Calendar open its settings > "Access permissions" > tick "Make available to the public" and choose "See only free/busy". Then paste: ' + form.getPublishedUrl() + ' calendar:' + cal.getId());
  }
  Logger.log('Edit the form: ' + form.getEditUrl());
}

function addQuestion(form, f) {
  var item;
  switch (f.kind) {
    case 'paragraph': item = form.addParagraphTextItem(); break;
    case 'radio': item = form.addMultipleChoiceItem().setChoiceValues(f.options); break;
    case 'dropdown': item = form.addListItem().setChoiceValues(f.options); break;
    case 'checkbox': item = form.addCheckboxItem().setChoiceValues(f.options); break;
    case 'date': item = form.addDateItem(); break;
    case 'time': item = form.addTimeItem(); break;
    default: item = form.addTextItem();
  }
  item.setTitle(f.label).setRequired(!!f.required);
}

// Share only "free/busy" of the booking calendar with everyone (event titles and details stay private).
// Uses the "Google Calendar API" advanced service; returns false (and setup still finishes) if it is not added.
function shareBusyPublicly(calendarId) {
  try {
    if (typeof Calendar === 'undefined') return false;
    Calendar.Acl.insert({ role: 'freeBusyReader', scope: { type: 'default' } }, calendarId);
    return true;
  } catch (e) {
    Logger.log('Could not make the calendar public: ' + e.message + ' (your Google Workspace admin may block public sharing)');
    return false;
  }
}

// Runs for every form answer: adds the booking to the calendar.
function onFormSubmit(e) {
  const props = PropertiesService.getScriptProperties();
  const cal = CalendarApp.getCalendarById(props.getProperty('CAL_ID'));
  const answers = {};
  e.response.getItemResponses().forEach(function (r) { answers[r.getItem().getTitle()] = r.getResponse(); });

  const first = function (kinds) {
    for (var i = 0; i < CONFIG.fields.length; i++) { if (kinds.indexOf(CONFIG.fields[i].kind) >= 0) return CONFIG.fields[i]; }
    return null;
  };
  const dateField = first(['date']), timeField = first(['time']);
  const nameField = CONFIG.fields[0];
  const menuField = first(['radio', 'dropdown']);
  if (!dateField) return;
  const d = String(answers[dateField.label] || '').match(/(\\d{4})-(\\d{1,2})-(\\d{1,2})/);
  if (!d) return;
  const t = timeField ? String(answers[timeField.label] || '').match(/(\\d{1,2}):(\\d{2})/) : null;
  const start = new Date(+d[1], +d[2] - 1, +d[3], t ? +t[1] : 9, t ? +t[2] : 0);
  const end = new Date(start.getTime() + CONFIG.durationMinutes * 60000);

  const clash = cal.getEvents(start, end).length > 0;
  const title = (clash ? '\\u26a0 DOUBLE BOOKING: ' : '') + [answers[nameField.label], menuField ? answers[menuField.label] : ''].filter(Boolean).join(' - ');
  const lines = CONFIG.fields.map(function (f) {
    const v = answers[f.label];
    return f.label + ': ' + (Array.isArray(v) ? v.join(', ') : (v || ''));
  });
  const options = { description: lines.join('\\n') };
  if (CONFIG.inviteCustomer) {
    for (var i = 0; i < CONFIG.fields.length; i++) {
      const f = CONFIG.fields[i], v = String(answers[f.label] || '');
      if (/e-?mail|\\u30e1\\u30fc\\u30eb|\\u96fb\\u5b50\\u90f5|\\u90f5\\u4ef6|correo/i.test(f.label) && /^[^\\s@]+@[^\\s@]+\\.[^\\s@]+\$/.test(v)) {
        options.guests = v;
        options.sendInvites = true;
        break;
      }
    }
  }
  cal.createEvent(title, start, end, options);
}
''';
}

/// 貼り付けた一行（"PASTE THIS INTO PRICING AI: <フォームのリンク> calendar:<カレンダーID>"）から取り出す
String? extractFormLink(String text) =>
    RegExp(r'https?://(docs\.google\.com/forms/[^\s<>"]+|forms\.gle/[^\s<>"]+)', caseSensitive: false).firstMatch(text)?[0];

String? extractCalendarId(String text) =>
    RegExp(r'calendar:\s*([\w.%+-]+@[\w.-]+)', caseSensitive: false).firstMatch(text)?[1] ?? RegExp(r'[\w.%+-]+@group\.calendar\.google\.com', caseSensitive: false).firstMatch(text)?[0];

